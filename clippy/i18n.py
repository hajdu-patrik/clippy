def normalize(lang: str | None) -> str:
    code = (lang or "").strip().lower().replace("_", "-").split("-")[0]
    return code if code in SUPPORTED else DEFAULT


def lookup(lang: str | None, key: str) -> str | None:
    """The text in exactly this language, or None (for strings whose English lives in code, like CLI help)."""
    return CATALOG[normalize(lang)].get(key)


def t(lang: str | None, key: str, **params) -> str:
    text = CATALOG[normalize(lang)].get(key) or CATALOG[DEFAULT].get(key) or key
    count = params.get("n", params.get("count"))
    params = {"s": "" if count == 1 else "s", **params}
    try:
        return text.format(**params)
    except (KeyError, IndexError, ValueError):
        return text


def detect(text: str) -> str:
    """The language of a short user message: Hungarian when it has Hungarian letters or words, else English."""
    text = text or ""
    return "hu" if _HU_HINT.search(text) or len(_HU_LETTERS.findall(text)) >= 2 else "en"


def saved_language() -> str | None:
    try:
        lang = json.loads(SETTINGS.read_text(encoding="utf-8")).get("lang")
    except (OSError, ValueError, AttributeError):
        return None
    return lang if lang in SUPPORTED else None


def save_language(lang: str) -> str:
    lang = normalize(lang)
    try:
        data = json.loads(SETTINGS.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        data = {}
    SETTINGS.parent.mkdir(parents=True, exist_ok=True)
    SETTINGS.write_text(json.dumps({**data, "lang": lang}, indent=2), encoding="utf-8")
    return lang


def system_language() -> str:
    """CLIPPY_LANG, else `clippy lang`'s saved choice, else the OS user interface language, else the locale."""
    if os.environ.get("CLIPPY_LANG"):
        return normalize(os.environ["CLIPPY_LANG"])
    if saved := saved_language():
        return saved
    try:
        import ctypes

        lcid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        return "hu" if lcid & 0x3FF == 0x0E else "en"
    except (AttributeError, OSError):
        pass
    return normalize((locale.getlocale()[0] or "")[:2])

