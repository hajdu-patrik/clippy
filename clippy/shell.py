"""Shell integration for the `clippy` command: one command spec -> help text, PowerShell and Clink (cmd.exe)
tab completion, and `clippy install` (PATH, a shim every open terminal sees, profile hook, Clink script)."""

from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

from . import i18n
from .tools import ROOT

BIN = ROOT / "bin"
PS_SCRIPT = ROOT / "scripts" / "clippy-completion.ps1"
BEGIN, END = "# >>> clippy completion >>>", "# <<< clippy completion <<<"
BLOCK_RE = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\r?\n?", re.S)

COMMANDS: dict[str, tuple[str, dict[str, str]]] = {
    "start": ("Start in the background and open it in the browser",
              {"--no-browser": "Do not open a browser", "--lan": "Phones and tablets on the same Wi-Fi too (pairing)"}),
    "down": ("Stop completely (running renders too) and free the GPU", {"--all": "Stop Ollama as well"}),
    "restart": ("Stop + start", {"--no-browser": "Do not open a browser", "--lan": "Phones and tablets too"}),
    "status": ("Is it running, what is it doing, how much VRAM the model holds", {}),
    "open": ("Open the web UI in a new browser tab", {}),
    "pair": ("Pair a phone or tablet: a one-time link and QR code (after start --lan)",
             {"--reset": "Forget every paired device"}),
    "logs": ("The end of the server log", {}),
    "clip": ("Make clips from the command line: clippy clip <link> [options]", {}),
    "install": ("Install the clippy command, PowerShell and cmd (Clink) tab completion", {}),
    "lang": ("Language: hu or en (CLI + the web app's default)", {"hu": "Hungarian (magyar)", "en": "English"}),
    "help": ("This help", {}),
}


def command_doc(cmd: str, lang: str | None = None) -> str:
    return i18n.lookup(lang or i18n.system_language(), f"cmd.{cmd}") or COMMANDS[cmd][0]


def clip_flags(lang: str | None = None) -> list[tuple[str, str, list[str]]]:
    """(long flag, help, choices) of `clippy clip`, straight from its argparse parser."""
    from .cli import build_parser

    out = []
    for action in build_parser(lang)._actions:
        longs = [o for o in action.option_strings if o.startswith("--")]
        if not longs or longs[0] in ("--help", "--version"):
            continue
        out.append((longs[0], (action.help or "").split(" (")[0], [str(c) for c in action.choices or []]))
    return out


def flags_of(cmd: str, lang: str | None = None) -> list[tuple[str, str, list[str]]]:
    lang = lang or i18n.system_language()
    if cmd == "clip":
        return clip_flags(lang)
    return [(f, i18n.lookup(lang, f"flag.{cmd}{f}") or d, []) for f, d in COMMANDS[cmd][1].items()]


def _pq(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def powershell_script() -> str:
    cmds = "; ".join(f"{_pq(c)} = {_pq(command_doc(c))}" for c in COMMANDS)
    flags = "\n".join(f"        {_pq(c)} = [ordered]@{{ {'; '.join(f'{_pq(f)} = {_pq(h)}' for f, h, _ in flags_of(c))} }}"
                      for c in COMMANDS)
    values = "\n".join(f"        {_pq(c + '|' + f)} = @({', '.join(_pq(v) for v in ch)})"
                       for c in COMMANDS for f, _, ch in flags_of(c) if ch)
    return f"""# PowerShell tab completion for clippy -- generated by `clippy install` (clippy/shell.py)
Register-ArgumentCompleter -Native -CommandName clippy, clippy.cmd -ScriptBlock {{
    param($wordToComplete, $commandAst, $cursorPosition)
    $commands = [ordered]@{{ {cmds} }}
    $flags = @{{
{flags}
    }}
    $values = @{{
{values}
    }}
    $before = @($commandAst.CommandElements | Select-Object -Skip 1 |
        Where-Object {{ $_.Extent.EndOffset -lt $cursorPosition }} | ForEach-Object {{ $_.Extent.Text }})
    $cmd = if ($before.Count) {{ $before[0] }} else {{ '' }}
    $prev = if ($before.Count) {{ $before[-1] }} else {{ '' }}
    $emit = {{ param($t, $tip) [System.Management.Automation.CompletionResult]::new($t, $t, 'ParameterValue', $tip) }}
    if (-not $cmd) {{
        foreach ($c in $commands.Keys) {{ if ($c -like "$wordToComplete*") {{ & $emit $c $commands[$c] }} }}
        return
    }}
    if ($values.ContainsKey("$cmd|$prev")) {{
        foreach ($v in $values["$cmd|$prev"]) {{ if ($v -like "$wordToComplete*") {{ & $emit $v $v }} }}
        return
    }}
    if ($flags.ContainsKey($cmd)) {{
        foreach ($f in $flags[$cmd].Keys) {{ if ($f -like "$wordToComplete*") {{ & $emit $f $flags[$cmd][$f] }} }}
    }}
}}
"""


def _lq(text: str) -> str:
    return '"' + " ".join(text.split()).replace("\\", "\\\\").replace('"', '\\"') + '"'


def clink_script() -> str:
    out = ["-- Clink (cmd.exe) tab completion for clippy -- generated by `clippy install` (clippy/shell.py)",
           "local function p() return clink.argmatcher() end"]
    args = []
    for c in COMMANDS:
        entries, docs = [], []
        for f, h, ch in flags_of(c):
            entries.append(f"{_lq(f)} .. p():addarg({{{', '.join(_lq(v) for v in ch)}}})" if ch else _lq(f))
            docs.append(f"[{_lq(f)}] = {_lq(h)}")
        parser = "p()"
        if entries:
            parser += ":addflags({" + ", ".join(entries) + "}):adddescriptions({" + ", ".join(docs) + "})"
        if c != "clip":
            parser += ":nofiles()"
        out.append(f"local k_{c} = {parser}")
        args.append(f"{_lq(c)} .. k_{c}")
    out.append('clink.argmatcher("clippy", "clippy.cmd")')
    out.append(":addarg({\n    " + ",\n    ".join(args) + ",\n})")
    out.append(":adddescriptions({\n    " + ",\n    ".join(f"[{_lq(c)}] = {_lq(command_doc(c))}" for c in COMMANDS) + ",\n})")
    out.append(":nofiles()")
    return "\n".join(out) + "\n"


def _cmd_autorun() -> str:
    try:
        import winreg
    except ImportError:
        return ""
    found = []
    for hive in (winreg.HKEY_CURRENT_USER, winreg.HKEY_LOCAL_MACHINE):
        try:
            with winreg.OpenKey(hive, r"Software\Microsoft\Command Processor") as key:
                found.append(str(winreg.QueryValueEx(key, "AutoRun")[0]))
        except OSError:
            continue
    return " & ".join(found)


def clink_profile() -> Path | None:
    """Clink's profile folder (it loads every *.lua there); None when Clink does not start with cmd.exe."""
    autorun = _cmd_autorun()
    if "clink" not in autorun.lower():
        return None
    m = re.search(r'--profile\s+(?:"([^"]+)"|(\S+))', autorun)
    if m:
        raw = m.group(1) or m.group(2)
        return Path.home() / raw[1:].lstrip("\\/") if raw.startswith("~") else Path(os.path.expandvars(raw))
    return Path(os.environ.get("LOCALAPPDATA", str(Path.home() / "AppData" / "Local"))) / "clink"


def _add_to_user_path(folder: Path) -> bool:
    import ctypes
    import winreg

    with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment", 0, winreg.KEY_READ | winreg.KEY_WRITE) as key:
        try:
            value, kind = winreg.QueryValueEx(key, "Path")
        except OSError:
            value, kind = "", winreg.REG_EXPAND_SZ
        parts = [p for p in value.split(";") if p]
        if any(os.path.normcase(p.rstrip("\\")) == os.path.normcase(str(folder)) for p in parts):
            return False
        winreg.SetValueEx(key, "Path", 0, kind, ";".join(parts + [str(folder)]))
    ctypes.windll.user32.SendMessageTimeoutW(0xFFFF, 0x001A, 0, "Environment", 0x0002, 5000, None)
    return True


def _powershell_profiles() -> list[Path]:
    found = []
    for exe in ("powershell", "pwsh"):
        try:
            out = subprocess.run([exe, "-NoProfile", "-NonInteractive", "-Command", "$PROFILE.CurrentUserCurrentHost"],
                                 capture_output=True, text=True, timeout=60).stdout.strip().splitlines()
        except (OSError, subprocess.TimeoutExpired):
            continue
        if out and out[-1].lower().endswith(".ps1"):
            found.append(Path(out[-1].strip()))
    return found


def _write_if_changed(path: Path, text: str, label: str, say) -> None:
    old = path.read_text(encoding="utf-8-sig") if path.exists() else None
    if old == text:
        say(i18n.t(i18n.system_language(), "cli.install_uptodate", label=label, path=path))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    key = "cli.install_updated" if old is not None else "cli.install_created"
    say(i18n.t(i18n.system_language(), key, label=label, path=path))


def install(say=print) -> int:
    lang = i18n.system_language()
    if sys.platform != "win32":
        say(i18n.t(lang, "cli.install_unix"))
        return 1
    say(i18n.t(lang, "cli.install_path_added" if _add_to_user_path(BIN) else "cli.install_path_has", path=BIN))
    apps = Path(os.environ.get("LOCALAPPDATA", "")) / "Microsoft" / "WindowsApps"
    if apps.is_dir():
        _write_if_changed(apps / "clippy.cmd", f'@echo off\ncall "{BIN / "clippy.cmd"}" %*\n', "shim", say)
    _write_if_changed(PS_SCRIPT, powershell_script(), "PowerShell completion", say)
    block = f"{BEGIN}\n. '{PS_SCRIPT}'\n{END}\n"
    for prof in _powershell_profiles():
        old = prof.read_text(encoding="utf-8-sig") if prof.exists() else ""
        lines = [ln for ln in BLOCK_RE.sub("", old).splitlines() if "clippy-completion.ps1" not in ln]
        text = "\n".join(lines).rstrip("\n")
        _write_if_changed(prof, (text + "\n\n" if text else "") + block, "PowerShell profile", say)
    clink = clink_profile()
    if clink:
        _write_if_changed(clink / "clippy.lua", clink_script(), "cmd (Clink) completion", say)
    else:
        say(i18n.t(lang, "cli.install_no_clink"))
    say(i18n.t(lang, "cli.install_done"))
    return 0
